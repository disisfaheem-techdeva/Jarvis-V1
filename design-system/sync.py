#!/usr/bin/env python3
"""Push the TechDeva design system into every surface that uses it.

    python3 design-system/sync.py           # write
    python3 design-system/sync.py --check   # exit 1 if anything is out of date

Sources (edit these, never the copies):
    design-system/tokens.css      colours, type, radius, motion, chart tokens
    design-system/effects.css     grain, ambient light, glass, motion, reduced motion
    design-system/components.css  .td-* classes for plain-HTML pages

Targets:
    techdeva-web/src/app/design-system/{tokens,effects,tailwind}.css
        Next.js imports these.
    web/assets/td.css
        Tailwind build of design-system/web.css (tokens + effects + theme +
        components + web/styles/<page>.css), served by app/main.py at
        /assets/td.css. Each page in TAILWIND_PAGES links it with a content hash.
    HTML_TARGETS
        Single-file pages not served by FastAPI (dashboard-cockpit.html) inline tokens + effects + components between
        /* @td-design-system:start */ … /* @td-design-system:end */.

Fonts go between <!-- @td-fonts:start --> … <!-- @td-fonts:end --> in <head>.
Needs Node for the Tailwind build (installs design-system/node_modules on
first run). To add a page or app, add it to the lists below and run this.
"""

from __future__ import annotations

import hashlib
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DS = ROOT / "design-system"

COPY_TARGETS = {
    "tokens.css": ROOT / "techdeva-web/src/app/design-system/tokens.css",
    "effects.css": ROOT / "techdeva-web/src/app/design-system/effects.css",
    "tailwind.css": ROOT / "techdeva-web/src/app/design-system/tailwind.css",
}

# Single-file pages that are not served by FastAPI: everything is inlined.
HTML_TARGETS = [
    ROOT / "dashboard-cockpit.html",
]

# FastAPI-served pages built with Tailwind: design-system/web.css compiles to
# web/assets/td.css (served by app/main.py at /assets/td.css); each page links
# it with a content hash, between <!-- @td-css:start --> … <!-- @td-css:end -->.
TAILWIND_ENTRY = DS / "web.css"
TAILWIND_OUT = ROOT / "web/assets/td.css"
TAILWIND_PAGES = [
    ROOT / "web/portal.html",
    ROOT / "web/onboarding.html",
    ROOT / "web/signup.html",
    ROOT / "web/techdeva.html",
    ROOT / "web/dashboard.html",
    ROOT / "web/pin.html",
    ROOT / "web/reset.html",
]

FONTS = (
    '<link rel="preconnect" href="https://fonts.googleapis.com">\n'
    '<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>\n'
    '<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Bricolage+Grotesque:wght@500;600;700'
    '&family=Geist:wght@400;500;600;700&family=Geist+Mono:wght@400;500&display=swap">'
)

CSS_START, CSS_END = "/* @td-design-system:start */", "/* @td-design-system:end */"
LINK_START, LINK_END = "<!-- @td-css:start -->", "<!-- @td-css:end -->"
FONT_START, FONT_END = "<!-- @td-fonts:start -->", "<!-- @td-fonts:end -->"
GENERATED = "/* GENERATED by design-system/sync.py from design-system/{name}. Do not edit here. */\n"


def read(name: str) -> str:
    return (DS / name).read_text()


def html_css_block() -> str:
    body = "\n".join(read(n).rstrip() for n in ("tokens.css", "effects.css", "components.css"))
    return f"{CSS_START}\n/* GENERATED by design-system/sync.py. Edit design-system/*.css, not this block. */\n{body}\n{CSS_END}"


def inject(html: str, start: str, end: str, block: str, anchor: str, after: bool) -> str:
    pattern = re.compile(re.escape(start) + r".*?" + re.escape(end), re.S)
    if pattern.search(html):
        return pattern.sub(lambda _: block, html, count=1)
    i = html.find(anchor)
    if i < 0:
        raise SystemExit(f"cannot place design system: no {anchor!r}")
    pos = i + len(anchor) if after else i
    return html[:pos] + "\n" + block + "\n" + html[pos:]


def expected_html(path: Path) -> str:
    html = path.read_text()
    html = inject(html, CSS_START, CSS_END, html_css_block(), "<style>", after=True)
    html = inject(html, FONT_START, FONT_END, f"{FONT_START}\n{FONTS}\n{FONT_END}", "<style>", after=False)
    return html


def build_tailwind() -> str:
    """Compile design-system/web.css with the pinned Tailwind CLI and return the CSS."""
    bin_ = DS / "node_modules/.bin/tailwindcss"
    if not bin_.exists():
        subprocess.run(["npm", "ci", "--silent"], cwd=DS, check=True)
    with tempfile.TemporaryDirectory() as tmp:
        out = Path(tmp) / "td.css"
        subprocess.run([str(bin_), "-i", str(TAILWIND_ENTRY), "-o", str(out), "--minify"],
                       cwd=DS, check=True, capture_output=True)
        return out.read_text()


def linked_html(path: Path, css: str) -> str:
    digest = hashlib.sha256(css.encode()).hexdigest()[:10]
    link = f'{LINK_START}\n<link rel="stylesheet" href="/assets/td.css?v={digest}">\n{LINK_END}'
    html = path.read_text()
    html = inject(html, FONT_START, FONT_END, f"{FONT_START}\n{FONTS}\n{FONT_END}", "</head>", after=False)
    return inject(html, LINK_START, LINK_END, link, "</head>", after=False)


def main() -> int:
    check = "--check" in sys.argv
    stale: list[str] = []

    for name, dest in COPY_TARGETS.items():
        want = GENERATED.format(name=name) + read(name)
        if not dest.exists() or dest.read_text() != want:
            stale.append(str(dest.relative_to(ROOT)))
            if not check:
                dest.parent.mkdir(parents=True, exist_ok=True)
                dest.write_text(want)

    css = build_tailwind()
    if not TAILWIND_OUT.exists() or TAILWIND_OUT.read_text() != css:
        stale.append(str(TAILWIND_OUT.relative_to(ROOT)))
        if not check:
            TAILWIND_OUT.parent.mkdir(parents=True, exist_ok=True)
            TAILWIND_OUT.write_text(css)
    for path in TAILWIND_PAGES:
        want = linked_html(path, css)
        if path.read_text() != want:
            stale.append(str(path.relative_to(ROOT)))
            if not check:
                path.write_text(want)

    for path in HTML_TARGETS:
        if not path.exists():
            continue
        want = expected_html(path)
        if path.read_text() != want:
            stale.append(str(path.relative_to(ROOT)))
            if not check:
                path.write_text(want)

    if check:
        if stale:
            print("Design system out of date in:\n  " + "\n  ".join(stale))
            print("Run: python3 design-system/sync.py")
            return 1
        print("Design system in sync.")
        return 0
    print(("Updated:\n  " + "\n  ".join(stale)) if stale else "Already in sync.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
